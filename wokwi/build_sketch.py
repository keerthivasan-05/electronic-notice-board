#!/usr/bin/env python3
"""Print a single-file Wokwi sketch built from the production firmware."""

from pathlib import Path

FIRMWARE = Path(__file__).resolve().parents[1] / "firmware" / "SmartNoticeBoard"
SOURCES = ("Crc8.h", "NoticeStore.h", "NoticeStore.cpp", "SmartNoticeBoard.ino")


def main():
    print("// Generated by wokwi/build_sketch.py.")
    print("#include <Arduino.h>")
    print("#define NOTICE_BOARD_SIMULATION")
    for filename in SOURCES:
        print(f'\n// {filename}')
        lines = (FIRMWARE / filename).read_text(encoding="utf-8").splitlines()
        for line in lines:
            if line != "#pragma once" and not line.startswith('#include "'):
                print(line)


if __name__ == "__main__":
    main()
